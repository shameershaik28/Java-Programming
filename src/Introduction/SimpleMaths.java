package Introduction;

/*
Perform the following operations on 6 and 3 and print their respective outputs in different lines.

1. Addition
2. Subtraction
3. Multiplication
4. Double Division
 */

public class SimpleMaths {

    public static void main(String[] args) {

        int k = 6;
        int j = 3;

        System.out.println(k + j);
        System.out.println(k - j);
        System.out.println(k * j);
        System.out.println(k / j);
    }
}
